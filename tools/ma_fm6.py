"""Manta's FM6 patches -> firmware/src/ma_fm6.inc (packed 128-byte voices): Manta's own ORCH HIT, and three of Tuna's
own (tools/tuna_fm6.py in Tuna, GPL-3.0, the same author), as they are.

    python3 tools/ma_fm6.py            writes it
    python3 tools/ma_fm6.py --check    fails if the file differs from what this writes

Patches made for Manta and Tuna (no factory ROM data of any instrument), written as Felucca's own are
(tools/gen_fm6_patches.py: op() and voice(), OP1..OP6). A family loads one onto FM6 as the track's own patch
(ma_sounds.h). Tuna checked its three by ear in its audition; Manta's is levelled by tests/ma_audition.sh.

The algorithms used (the generic 6-operator numbering):
   1  1<-2,  3<-4<-5<-6 (fb 6)             carriers 1 3
   2  1<-2 (fb 2),  3<-4<-5<-6             carriers 1 3
   5  1<-2,  3<-4,  5<-6 (fb 6)            carriers 1 3 5
  18  1<-(2, 3 fb, 4<-5<-6)                carrier 1
  32  six carriers (fb 6)                   additive
Envelope rates: higher is faster; levels 0..99. ol: output level; fc: coarse ratio (0 = 0.5); det: 7 = none.
"""
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "src" / "ma_fm6.inc"
_spec = importlib.util.spec_from_file_location("gen_fm6", ROOT / "tools" / "gen_fm6_patches.py")
_g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_g)
op, voice, pack = _g.op, _g.voice, _g.pack
OFF = op(ol=0)

# (C name, voice)
PATCHES = [
    # an orchestra hit: brass, a body an octave down and a bright octave up, struck together, gone in a breath,
    # its pitch falling a hair as it hits
    ("ORCHHIT", voice("ORCH HIT", 5, [
        op(r=(99, 56, 40, 60), l=(99, 40, 0, 0), ol=99, kvs=2),
        op(r=(99, 50, 40, 60), l=(99, 52, 0, 0), ol=88, kvs=4),
        op(r=(99, 52, 40, 60), l=(99, 40, 0, 0), ol=92, fc=0),
        op(r=(99, 60, 40, 60), l=(99, 40, 0, 0), ol=82),
        op(r=(99, 58, 40, 60), l=(99, 34, 0, 0), ol=86, fc=2, det=10),
        op(r=(99, 66, 40, 60), l=(99, 30, 0, 0), ol=84, fc=2)],
        fb=7, pr=(99, 60, 99, 99), pl=(54, 50, 50, 50), lpms=0)),
    # a slapped and popped bass: the thumb's click (ratio 3, gone at once), a growl on velocity (Tuna's)
    ("SLAPBASS", voice("SLAP BASS", 5, [
        op(r=(99, 50, 30, 62), l=(99, 85, 70, 0), ol=99, kvs=2, rs=2),
        op(r=(99, 75, 40, 70), l=(99, 55, 35, 0), ol=92, kvs=7, rs=2),
        op(r=(99, 55, 35, 62), l=(99, 80, 60, 0), ol=80, fc=2, kvs=2),
        op(r=(99, 88, 60, 70), l=(99, 0, 0, 0), ol=90, fc=3, kvs=6),
        OFF, OFF],
        fb=0, lpms=0)),
    # a fretless bass: round, a 'mwah' on velocity, glides (Tuna's)
    ("FRETLESS", voice("FRETLESS", 5, [
        op(r=(80, 40, 25, 62), l=(99, 90, 76, 0), ol=99, kvs=2),
        op(r=(80, 48, 30, 62), l=(99, 70, 50, 0), ol=80, kvs=5),
        op(r=(80, 40, 25, 62), l=(99, 88, 72, 0), ol=82, fc=2, kvs=2),
        op(r=(80, 50, 30, 62), l=(99, 60, 40, 0), ol=55, fc=2, kvs=4),
        OFF, OFF],
        fb=0, lpms=0)),
    # the accordion (the cumbia's and the vallenato's): three steel reeds a key, buzzing, not a synth's pad. Each
    # reed a carrier with its own modulator at ratio 1 (the reed's saw-like buzz, brighter with the third's
    # feedback); two at 8' tuned apart (+17 cents: the musette's beating), one at 4' softer; the bellows' quick
    # swell, held level (the bellows, not the key, make it loud), let go at once
    ("ACCORDION", voice("ACCORDION", 5, [
        op(r=(78, 50, 50, 72), l=(99, 96, 96, 0), ol=96, det=5, kvs=1),
        op(r=(70, 45, 40, 70), l=(99, 90, 88, 0), ol=80, rs=1),
        op(r=(78, 50, 50, 72), l=(99, 96, 96, 0), ol=93, ff=1, kvs=1),
        op(r=(70, 45, 40, 70), l=(99, 90, 88, 0), ol=78, rs=1),
        op(r=(80, 50, 50, 72), l=(99, 94, 94, 0), ol=76, fc=2, det=9, kvs=1),
        op(r=(72, 45, 40, 70), l=(99, 88, 86, 0), ol=74, fc=2, rs=1)],
        fb=6, lpms=0)),
    # the bandoneon (the tango's): its reeds in octaves (8' and 16'), dry-tuned, no musette; darker and more nasal
    # than the accordion, the bellows' slower push in and its breath on the attack, the marcato's quick let go
    ("BANDONEON", voice("BANDONEON", 5, [
        op(r=(66, 50, 50, 70), l=(99, 96, 96, 0), ol=95, kvs=2),
        op(r=(58, 45, 40, 68), l=(99, 86, 82, 0), ol=76, rs=1, kvs=2),
        op(r=(66, 50, 50, 70), l=(99, 96, 96, 0), ol=88, fc=0, det=8, kvs=2),
        op(r=(58, 45, 40, 68), l=(99, 84, 80, 0), ol=72, fc=0, rs=1),
        op(r=(70, 50, 50, 70), l=(99, 92, 92, 0), ol=70, fc=1, det=6, kvs=1),
        op(r=(60, 45, 40, 68), l=(99, 80, 76, 0), ol=66, fc=3, rs=1)],
        fb=4, lpms=0)),
]


def render():
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/ma_fm6.py: Manta's FM6 patches (Tuna's own), packed (128 bytes); edit that, not this */"]
    for cname, v in PATCHES:
        name = "".join(chr(x) for x in v[145:155]).rstrip()
        L += [f"static const uint8_t MA_FM6_{cname}[128] = {{   /* {name} */", _g.c_rows(pack(v)), "};"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("ma_fm6: firmware/src/ma_fm6.inc is out of date (python3 tools/ma_fm6.py)")
        print(f"ma_fm6: {len(PATCHES)} patches, up to date")
    else:
        OUT.write_text(text)
        print(f"ma_fm6: {len(PATCHES)} patches -> {OUT.relative_to(ROOT)}")
